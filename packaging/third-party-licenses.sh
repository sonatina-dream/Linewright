#!/bin/bash
# Regenerate THIRD_PARTY_LICENSES.md (crate licenses + bundled icons, syntaxes and themes).
# Requires: cargo install --locked cargo-about --features cli
set -euo pipefail
cd "$(dirname "$0")/.."

OUT=THIRD_PARTY_LICENSES.md
{
    echo "# Third-party licenses"
    echo
    echo "Linewright is built on the open-source projects listed below. Their license"
    echo "notices are reproduced here as their licenses require."
    echo
    cargo about generate --format json --frozen | python3 packaging/render_notices.py
    echo "Note: option-ext (MPL-2.0) is used unmodified. Its source code is available at"
    echo "https://crates.io/crates/option-ext."
    echo
    echo "## Toolbar icons (Lucide)"
    echo
    echo "The toolbar icons are drawn with paths from Lucide (https://lucide.dev)."
    echo
    echo '```text'
    cat third_party/lucide/LICENSE
    echo '```'
    echo
    # Generated by examples/export_themes.rs; demote its headings by one level.
    sed -e 's/^## /### /' -e 's/^# /## /' third_party/bundled-assets.md
} > "$OUT"
echo "wrote $OUT ($(wc -c < "$OUT" | tr -d ' ') bytes)"
